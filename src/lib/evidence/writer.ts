/**
 * Evidence writer (docs/02 §2, docs/00 R1–R3) — the ONLY path from analyst
 * output to the Evidence table. Append-only: rows are never updated except the
 * user's dispute flag (which never deletes). Idempotent per (sessionId, turnId):
 * per-turn and end-of-session batch analysis cannot produce duplicates.
 */
import { db } from '@/lib/db'
import type { EvidenceItem } from '@/lib/engine/types'
import type { AnalystResult } from '@/lib/llm/analyst'

export interface WriteResult {
  written: number
  skipped: boolean // evidence for this turn already existed
  ids: string[]
}

/** Persist one turn's validated analyst items. */
export async function writeTurnEvidence(
  userId: string,
  sessionId: string,
  turnId: string,
  analysis: Pick<AnalystResult, 'items' | 'newUnknownWords' | 'ok'>,
  opts: { propagated?: boolean } = {},
): Promise<WriteResult> {
  const existing = await db.evidence.count({ where: { sessionId, turnId } })
  if (existing > 0) return { written: 0, skipped: true, ids: [] }
  if (!analysis.ok || analysis.items.length === 0) {
    return { written: 0, skipped: false, ids: [] }
  }

  const ids: string[] = []
  for (const item of analysis.items) {
    const row = await db.evidence.create({
      data: {
        userId,
        sessionId,
        turnId,
        nodeId: item.nodeId,
        skill: item.skill,
        outcome: item.outcome,
        errorType: item.errorType ?? null,
        produced: item.produced ?? null,
        expected: item.expected ?? null,
        l1Interference: item.l1Interference ?? false,
        hintUsed: item.hintUsed ?? false,
        responseLatencyMs: item.responseLatencyMs ?? null,
        confidence: item.confidence,
        propagated: opts.propagated ?? item.propagated ?? false,
        // disputed arrives only from a user action (API) or replayed data —
        // the analyst itself never sets it; persist it when present so
        // aggregation excludes the item exactly as the engine expects
        disputed: item.disputed ?? false,
      },
    })
    ids.push(row.id)
  }
  return { written: ids.length, skipped: false, ids }
}

/**
 * Persist engine-generated (propagation / root-cause) evidence rows.
 * These are appended OUTSIDE the per-turn guard: the session status guard
 * already makes the pipeline run exactly once, and a per-(session,turnId)
 * dedupe would wrongly block the second engine batch of the same run.
 */
export async function writeEngineEvidence(
  userId: string,
  sessionId: string,
  items: EvidenceItem[],
): Promise<WriteResult> {
  if (items.length === 0) return { written: 0, skipped: false, ids: [] }
  const ids: string[] = []
  for (const item of items) {
    const row = await db.evidence.create({
      data: {
        userId,
        sessionId,
        turnId: 'engine', // deterministic marker: this row was generated by the pipeline
        nodeId: item.nodeId,
        skill: item.skill,
        outcome: item.outcome,
        errorType: item.errorType ?? null,
        produced: item.produced ?? null,
        expected: item.expected ?? null,
        l1Interference: item.l1Interference ?? false,
        hintUsed: item.hintUsed ?? false,
        responseLatencyMs: item.responseLatencyMs ?? null,
        confidence: item.confidence,
        propagated: true,
      },
    })
    ids.push(row.id)
  }
  return { written: ids.length, skipped: false, ids }
}

/**
 * User dispute (docs/00 R3): flag only — never delete, never rewrite.
 * Returns null when the row does not exist or belongs to another user.
 */
export async function disputeEvidence(
  userId: string,
  evidenceId: string,
  reason: string | null,
): Promise<{ id: string; disputed: true } | null> {
  const row = await db.evidence.findUnique({ where: { id: evidenceId } })
  if (!row || row.userId !== userId) return null
  if (row.disputed) return { id: row.id, disputed: true }
  await db.evidence.update({
    where: { id: evidenceId },
    data: { disputed: true, disputeReason: reason },
  })
  return { id: evidenceId, disputed: true }
}
