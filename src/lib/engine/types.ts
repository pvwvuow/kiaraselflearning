/**
 * Kiara engine types — pure data contracts shared by the deterministic core,
 * the API layer and the UI. NO imports from prisma/next/llm here (enforced by
 * tests/engine/purity.test.ts).
 */

// ── unions (DB stores strings; these are the validated domains) ──

export type Skill = 'reading' | 'writing' // MVP; listening|speaking post-MVP
export const SKILLS: readonly Skill[] = ['reading', 'writing']

export type NodeType =
  | 'sound_letter'
  | 'word'
  | 'chunk'
  | 'grammar_pattern'
  | 'pragmatic_skill'
  | 'error_pattern'
  | 'topic_cluster'

export type EdgeType = 'prerequisite' | 'related' | 'confusable' | 'part_of'

/** CEFR bands present in the MVP graph (docs/05 M1: A1–B1 world) */
export type CefrBand = 'A1' | 'A2' | 'B1'
export const CEFR_BANDS: readonly CefrBand[] = ['A1', 'A2', 'B1']

export type Outcome =
  | 'correct'
  | 'error'
  | 'slip_self_corrected'
  | 'avoided'
  | 'used_with_hint'
  | 'unknown'

export type FsrsRating = 'Again' | 'Hard' | 'Good' | 'Easy'

export type FsrsStateName = 'New' | 'Learning' | 'Review' | 'Relearning'

export type DisplayState =
  | 'locked'
  | 'available'
  | 'learning'
  | 'mastered'
  | 'fading'
  | 'assumed_known'

// ── evidence (as produced by the Analyst, after zod + whitelist) ──

export interface EvidenceItem {
  /** prisma Evidence id once persisted; undefined for in-flight items */
  id?: string
  nodeId: string
  skill: Skill
  outcome: Outcome
  errorType?: string | null
  produced?: string | null
  expected?: string | null
  l1Interference?: boolean
  hintUsed?: boolean
  responseLatencyMs?: number | null
  /** analyst confidence 0..1 */
  confidence: number
  /** true when generated by mastery propagation (A4) */
  propagated?: boolean
  /** user disputed — excluded from aggregation */
  disputed?: boolean
  createdAt?: Date | string
}

// ── world graph (engine view) ──

export interface EngineNode {
  id: string
  type: NodeType
  lang: string
  cefr: string | null
  frequencyRank: number | null
  title: string
  glossFa: string | null
  tags: string[]
}

export interface EngineEdge {
  fromId: string
  toId: string
  type: EdgeType
  weight: number
}

// ── user state (mirror of UserNodeState row) ──

export interface NodeSkillState {
  userId: string
  nodeId: string
  skill: Skill
  stability: number
  difficulty: number
  due: Date | null
  lastReviewAt: Date | null
  reps: number
  lapses: number
  learningSteps: number
  fsrsState: FsrsStateName
  displayState: DisplayState
  /** soft 0..1 signal for propagation & UI */
  strength: number
  pendingDelayTest: boolean
  delayTestEligibleAt: Date | null
  masteredAt: Date | null
  /** idempotency for offline replay */
  lastAppliedEvidenceId: string | null
}

// ── grading ──

export interface SessionAggregate {
  /** weighted mean outcome value, −1..+1 */
  agg: number
  /** Σ confidence of included items */
  totalWeight: number
  /** confident error items this session (confidence ≥ CONFIDENT_EVIDENCE) */
  errorItems: number
  /** confident hint-free positive items (correct | slip_self_corrected) — Easy gate */
  positiveItems: number
  /** any error item present */
  hasError: boolean
  /** any hint used */
  hasHint: boolean
  /** included item count */
  n: number
}

export interface ApplyReviewInput {
  /** null => node not yet tracked for this skill */
  state: NodeSkillState | null
  /** this session's non-disputed evidence for this (nodeId, skill) */
  items: EvidenceItem[]
  /** distinct PAST sessions (before this one) containing a confident error */
  priorErrorSessions: number
  now: Date
  nodeType: NodeType
  userId: string
}

export interface ApplyReviewResult {
  /** null => no FSRS update (insufficient weight); evidence still logged */
  rating: FsrsRating | null
  updated: NodeSkillState
  /** distinct error sessions INCLUDING this one (persist for next time) */
  errorSessionsAfter: number
  gapConfirmed: boolean
  /** ids of evidence items consumed by this update */
  appliedEvidenceIds: string[]
}

// ── propagation (A4) ──

export interface PropagationEmit extends EvidenceItem {
  propagated: true
}

// ── growth (B) ──

export interface ErrorGroupKey {
  nodeId: string
  errorType: string | null
}

export interface ErrorGroup extends ErrorGroupKey {
  sessionIds: string[]
  samples: { produced: string | null; expected: string | null; confidence: number }[]
}

export interface TriggerCandidate {
  kind: 'plant_existing' | 'track_pattern'
  nodeId: string // existing node to plant, or error_pattern node to create/link
  group: ErrorGroup
  /** error_pattern candidate requires creating a (user or global) node */
  requiresNodeCreation: boolean
}

export interface SeedScoreBreakdown {
  goalRelevance: number
  frequency: number
  readiness: number
  novelty: number
}

export interface SeedDraft {
  triggerType: 'repeated_error'
  triggerRef: {
    errorCount: number
    sessionIds: string[]
    sampleProduced: string | null
    sampleExpected: string | null
    /** source node of the error group (for dedupe) */
    nodeId?: string
    /** stable dedupe key "nodeId::errorType" (pipeline dedupes proposals on it) */
    dedupeKey?: string
  }
  candidateNodeId: string | null
  candidatePayload: { type: NodeType; title: string; cefr: string | null } | null
  score: number
  scoreBreakdown: SeedScoreBreakdown
  reasonFa: string
}

// ── placement (docs/00 C1 + R10, docs/05 M1) ──

export interface PlacementItem {
  /** the probed word node (also the stable item id) */
  nodeId: string
  band: CefrBand
  /** English surface form shown to the user */
  word: string
  /** Persian gloss options (includes the correct one) */
  options: string[]
  correctIndex: number
}

export interface PlacementQuiz {
  startBand: CefrBand
  /** items per band, drawn once (deterministic for a seed) */
  pools: Record<CefrBand, PlacementItem[]>
}

export interface PlacementAnswer {
  /** the item's own band (what the ladder targeted when it was issued) */
  band: CefrBand
  correct: boolean
}

export interface PlacementLadderResult {
  /** highest band with a positive correct/wrong balance; null => lit nothing */
  finalBand: CefrBand | null
  /** highest band the ladder ever walked into */
  reachedBand: CefrBand
  /** band the ladder is standing on after the last answer (next item target) */
  currentBand: CefrBand
  perBand: Record<CefrBand, { correct: number; wrong: number }>
}

// ── brief & planner (C) ──

export interface BriefUser {
  level: string
  goal: string
  interests: string[]
  correctionStyle: 'immediate' | 'end_of_session'
  tone: string
}

export interface BriefNodeRef {
  id: string
  title: string
  glossFa: string | null
  why?: string
}

export interface SessionBrief {
  user: BriefUser
  knownLexicon: { A1: number; A2: number; B1: number; sampleLemmas: string[] }
  weakNodes: BriefNodeRef[]
  frontierNodes: BriefNodeRef[]
  activeErrorPatterns: { id: string; desc: string }[]
  scenario: {
    title: string
    role: string
    mustElicit: BriefNodeRef[]
  }
}

export interface SessionPlan {
  reviews: NodeSkillState[]
  newNodes: BriefNodeRef[]
  remedial: BriefNodeRef[]
  interestFlavor: string | null
  delayedTestProbes: NodeSkillState[]
}

// ── delayed test (A6) ──

export interface DelayedTestOutcome {
  nodeId: string
  skill: Skill
  correct: number
  total: number
  minConfidence: number
  /** number of failed probes since mastery was granted (for revocation) */
  failedProbesSinceMastery: number
}
